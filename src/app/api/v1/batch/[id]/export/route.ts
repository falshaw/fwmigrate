import { NextResponse } from "next/server";
import { apiHandler } from "@/lib/apiHandler";
import prisma from "@/lib/prisma";
import { notFound, badRequest } from "@/lib/errors";
import { logger } from "@/lib/logger";

interface BatchResult {
  filename: string;
  sourceVendor: string;
  targetVendor: string;
  status: string;
  projectId?: string;
  error?: string;
  ruleCount?: number;
}

export const GET = apiHandler(async ({ params, organizationId }) => {
  const batch = await prisma.batchMigration.findUnique({
    where: { id: params.id },
  });

  if (!batch) return notFound("Batch migration not found");
  if (batch.organizationId !== organizationId)
    return notFound("Batch migration not found");

  if (batch.status !== "completed") {
    return badRequest(
      "Batch migration has not completed yet. Run the batch first.",
    );
  }

  const results = batch.results as unknown as BatchResult[];
  const successResults = results.filter((r) => r.status === "success");

  if (successResults.length === 0) {
    return badRequest("No successful migrations to export.");
  }

  // Fetch all successful projects with their translated rules
  const projectIds = successResults
    .map((r) => r.projectId)
    .filter((id): id is string => !!id);

  const projects = await prisma.migrationProject.findMany({
    where: { id: { in: projectIds } },
    include: {
      translatedRules: {
        include: {
          normalizedRule: {
            select: { position: true, name: true },
          },
        },
        orderBy: { normalizedRule: { position: "asc" } },
      },
    },
  });

  // Build combined export
  const timestamp = new Date().toISOString();
  const sections: string[] = [];

  sections.push("!" + "=".repeat(78));
  sections.push(`! FW Migrate Batch Export: ${batch.name}`);
  sections.push(`! Generated: ${timestamp}`);
  sections.push(`! Total configs: ${batch.totalConfigs}`);
  sections.push(`! Successful: ${batch.completedCount}`);
  sections.push(`! Failed: ${batch.failedCount}`);
  sections.push("!" + "=".repeat(78));
  sections.push("");

  for (const project of projects) {
    sections.push("!" + "-".repeat(78));
    sections.push(`! Project: ${project.name}`);
    sections.push(
      `! Migration: ${project.sourceVendor} -> ${project.targetVendor}`,
    );
    sections.push(`! Rules: ${project.translatedRules.length}`);
    sections.push("!" + "-".repeat(78));
    sections.push("");

    for (const translated of project.translatedRules) {
      const ruleName = translated.normalizedRule?.name ?? "unnamed";
      const position = translated.normalizedRule?.position ?? 0;
      const config =
        translated.reviewStatus === "MODIFIED" && translated.manualOverride
          ? translated.manualOverride
          : translated.targetConfig;

      sections.push(`! --- Rule ${position}: ${ruleName} ---`);
      sections.push(config);
      sections.push("");
    }

    sections.push("");
  }

  // Summary of failures
  const failedResults = results.filter((r) => r.status === "failed");
  if (failedResults.length > 0) {
    sections.push("!" + "=".repeat(78));
    sections.push("! FAILED CONFIGS");
    sections.push("!" + "=".repeat(78));
    for (const f of failedResults) {
      sections.push(
        `! ${f.filename} (${f.sourceVendor} -> ${f.targetVendor}): ${f.error}`,
      );
    }
    sections.push("");
  }

  sections.push("!" + "=".repeat(78));
  sections.push(
    "! Generated by FW Migrate -- AI-Powered Firewall Migration Platform",
  );
  sections.push(`! FW Migrate -- ${timestamp}`);

  const fullExport = sections.join("\n");

  const filename = `${batch.name.replace(/[^a-zA-Z0-9_-]/g, "_")}_batch_export.txt`;

  logger.info("Batch export downloaded", {
    batchId: params.id,
    projectCount: projects.length,
  });

  return new NextResponse(fullExport, {
    status: 200,
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": `attachment; filename="${filename}"`,
    },
  });
});
